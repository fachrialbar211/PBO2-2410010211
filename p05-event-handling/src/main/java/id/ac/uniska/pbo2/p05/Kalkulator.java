private void prosesTombol(String teks) {
        if ("0123456789".contains(teks)) {
            if (mulaiBaru || layarField.getText().equals("0")) {
                layarField.setText(teks);
                mulaiBaru = false;
            } else {
                layarField.setText(layarField.getText() + teks);
            }
        } else if (teks.equals("C")) {
            layarField.setText("0");
            angkaPertama = 0;
            operator = "";
            mulaiBaru = true;
        } else if (teks.equals("=")) {
            if (!operator.isEmpty()) {
                double angkaKedua = Double.parseDouble(layarField.getText());
                double hasil = hitung(angkaPertama, angkaKedua, operator);
                layarField.setText(hasil % 1 == 0 ? String.valueOf((long) hasil) : String.valueOf(hasil));
                operator = "";
                mulaiBaru = true;
            }
        } else { // Tombol operator +, -, *, /
            angkaPertama = Double.parseDouble(layarField.getText());
            operator = teks;
            mulaiBaru = true;
        }
    }

    private double hitung(double a, double b, String op) {
        return switch (op) {
            case "+" -> a + b;
            case "-" -> a - b;
            case "*" -> a * b;
            case "/" -> b == 0 ? 0 : a / b;
            default -> b;
        };
    }
