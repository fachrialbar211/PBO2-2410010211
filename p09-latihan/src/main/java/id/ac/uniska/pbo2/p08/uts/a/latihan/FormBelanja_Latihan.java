    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        String nama = txtNama.getText().trim();
        String hargaStr = txtHarga.getText().trim();
        String jumlahStr = txtJumlah.getText().trim();

        if (nama.isEmpty() || hargaStr.isEmpty() || jumlahStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Semua isian wajib diisi!", "Validasi Kosong", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (daftarBelanja.isBarangAda(nama)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Barang '" + nama + "' sudah ada di dalam daftar!", "Data Ganda", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        double harga;
        int jumlah;
        try {
            harga = Double.parseDouble(hargaStr);
            jumlah = Integer.parseInt(jumlahStr);

            if (harga <= 0 || jumlah <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Harga dan Jumlah harus lebih dari 0!", "Validasi Rentang", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Harga dan Jumlah harus berupa angka yang valid!", "Format Salah", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        String kategori = cmbKategori.getSelectedItem().toString();
        Barang_Latihan b = new Barang_Latihan(nama, kategori, harga, jumlah);
        daftarBelanja.tambahBarang(b);

        modelTabel.addRow(new Object[]{
            b.getNama(),
            b.getKategori(),
            daftarBelanja.formatRupiah(b.getHarga()),
            b.getJumlah(),
            daftarBelanja.formatRupiah(b.hitungSubtotal())
        });

        perbaruiTampilanRingkasan();
        bersihkanInput();      // TODO add your handling code here:
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnBersihkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBersihkanActionPerformed
        int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Apakah Anda yakin ingin mengosongkan seluruh daftar belanja?",
                "Konfirmasi",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
            modelTabel.setRowCount(0);
            daftarBelanja.bersihkanSemua();
            perbaruiTampilanRingkasan();
            bersihkanInput();
        }         // TODO add your handling code here:
    }//GEN-LAST:event_btnBersihkanActionPerformed

