    private void simpanData() {

    String kode = kodeInput.getText().trim();
    String judul = judulInput.getText().trim();
    String penulis = penulisInput.getText().trim();
    String tahunText = tahunInput.getText().trim();

    if (kode.isEmpty()) {
        pesanLabel.setText("Kode buku wajib diisi.");
        kodeInput.requestFocus();
        return;
    }

    if (judul.isEmpty()) {
        pesanLabel.setText("Judul buku wajib diisi.");
        judulInput.requestFocus();
        return;
    }

    if (tahunText.isEmpty()) {
        pesanLabel.setText("Tahun terbit wajib diisi.");
        tahunInput.requestFocus();
        return;
    }

    int tahun;

    try {
        tahun = Integer.parseInt(tahunText);
    } catch (NumberFormatException e) {
        pesanLabel.setText("Tahun harus berupa angka.");
        tahunInput.requestFocus();
        return;
    }

    int tahunSekarang = java.time.Year.now().getValue();

    if (tahun < 1900 || tahun > tahunSekarang) {
        pesanLabel.setText(
            "Tahun harus antara 1900 sampai " + tahunSekarang
        );
        tahunInput.requestFocus();
        return;
    }

    Ketersediaan status =
        (Ketersediaan) statusCombo.getSelectedItem();

    hasil = new DataBuku(
        kode,
        judul,
        penulis,
        tahun,
        status
    );

    dispose();
}
    
    public DataBuku tampilkanDialog() {
    setVisible(true);
    return hasil;
}
    
  

