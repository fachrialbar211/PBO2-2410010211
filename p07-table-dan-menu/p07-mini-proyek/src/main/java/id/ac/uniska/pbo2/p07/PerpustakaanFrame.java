    private void perbaruiTombol() {

    boolean adaPilihan = tabelBuku.getSelectedRow() >= 0;

    ubahButton.setEnabled(adaPilihan);
    hapusButton.setEnabled(adaPilihan);

    ubahItem.setEnabled(adaPilihan);
    hapusItem.setEnabled(adaPilihan);
}
    
    private void cariBuku() {

    String kata = pencarianField.getText().trim();

    if (kata.isEmpty()) {
        pengurut.setRowFilter(null);
    } else {
        pengurut.setRowFilter(
            javax.swing.RowFilter.regexFilter(
                "(?i)" + java.util.regex.Pattern.quote(kata),
                0, 1, 2
            )
        );
    }

    perbaruiStatus();
}
    
    private void perbaruiStatus() {

    informasiLabel.setText(
        "Menampilkan " + tabelBuku.getRowCount()
        + " dari " + model.getRowCount()
        + " buku | Tersedia: " + model.hitungBukuTersedia()
    );
}
    
    private int ambilBarisTerpilih() {

    int baris = tabelBuku.getSelectedRow();

    if (baris < 0) {
        return -1;
    }

    return tabelBuku.convertRowIndexToModel(baris);
}
    
    private void hapusBuku() {

    int baris = ambilBarisTerpilih();

    if (baris < 0) {
        return;
    }

    String judul = model.ambilBuku(baris).getJudul();

    int pilihan = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Apakah kamu yakin ingin menghapus buku \"" + judul + "\"?",
        "Konfirmasi Hapus",
        javax.swing.JOptionPane.YES_NO_OPTION,
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

    if (pilihan == javax.swing.JOptionPane.YES_OPTION) {
        model.hapusBuku(baris);
        perbaruiStatus();
        perbaruiTombol();
    }
}
    
      private void tambahBuku() {

    DataBuku buku = new FormBukuDialog(
        this,
        "Tambah Buku",
        null
    ).tampilkanDialog();

    if (buku != null) {
        model.tambahBuku(buku);
        perbaruiStatus();
    }
}
    
    private void ubahBuku() {

    int baris = ambilBarisTerpilih();

    if (baris < 0) {
        return;
    }

    DataBuku buku = new FormBukuDialog(
        this,
        "Ubah Buku",
        model.ambilBuku(baris)
    ).tampilkanDialog();

    if (buku != null) {
        model.ubahBuku(baris, buku);
        perbaruiStatus();
    }
}
